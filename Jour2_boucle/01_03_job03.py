# Créer un programme qui parcourt les nombres de 1 à 20 et affiche le carré de chacun.
# 
for i in range(1, 21):
    print(i ** 2)
# 
# Élément	Explication
# for	Démarre une boucle.
# i	Représente le nombre actuel.
# range(1, 21)	Parcourt les nombres de 1 à 20 inclus.
# **	Opérateur de puissance en Python.
# i ** 2	Calcule le carré du nombre (i × i).
# print()	Affiche le résultat.
