# 🐍 Jour 2 — Job 02 : Un nombre sur deux
# 
# Créer un programme qui parcourt les nombres de 0 à 20 et affiche un nombre sur deux dans le terminal.
# 
# 
for i in range(0, 21, 2):
    print(i)
# 
# Élément	Explication
#  for	Démarre une boucle.
#  i	Variable qui prend successivement chaque nombre.
#  range(0, 21, 2)	Parcourt les nombres de 0 à 20 avec un pas de 2.
#  0	Nombre de départ.
#  21	Limite supérieure exclue.
#  2	Pas : on avance de 2 à chaque tour.
#  print(i)	Affiche le nombre actuel.
