# Créer un programme qui demande un nombre à l'utilisateur et détermine s'il est pair ou impair.
# 
# 
nombre = int(input("Entre un nombre : "))

if nombre % 2 == 0:
    print(f"Le nombre {nombre} est pair")
else:
    print(f"Le nombre {nombre} est impair")
