#  Créer un programme qui vérifie l'âge d'une personne.
#    18 ans ou plus → « Tu peux voter »
#    Moins de 18 ans → « Tu ne peux pas voter »
#
age = 18

if age >= 18:
    print("Tu peux voter")
else:
    print("Tu ne peux pas voter")
